const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, 'ChitChatIOS', p), 'utf8');
const ui = read('Screens/GroupInfoViewController.swift');
for (const action of ['promote', 'demote', 'remove', 'transfer-owner', 'owner-leave']) assert.ok(ui.includes(`"${action}"`));
assert.match(ui, /member.userId != userID, member.role != "owner"/);
assert.match(ui, /role == "admin" && member.role == "member" \? \["remove"\] : \[\]/);
assert.match(ui, /guard !busy/);
assert.match(ui, /Transfer ownership to .* and leave this group\?/);
assert.match(ui, /guard !candidates.isEmpty/);
assert.match(ui, /socketChatUpdated/);
assert.match(ui, /guard updated.isActiveMember\(userID\) else \{ closeGroup/);
assert.match(ui, /self.service.administerGroup/);
const api = read('Services/ChatService.swift');
assert.match(api, /action == "remove" \? .delete : .post/);
assert.match(api, /body: \["userId": userID\]/);
const message = read('Models/Message.swift');
for (const event of ['group_member_added', 'group_member_left', 'group_member_removed', 'group_admin_promoted', 'group_admin_demoted', 'group_owner_transferred', 'group_name_changed', 'group_photo_changed']) assert.ok(message.includes(event));
assert.match(message, /try\? values\?\.decode\(Person.self/);
assert.match(message, /default: return "Group updated"/);
const detail = read('Screens/ChatDetailViewController.swift');
assert.match(detail, /message.type != .system else \{ return \}/);
assert.match(detail, /message.type == .system[\s\S]*?textAlignment = .center/);
assert.match(detail, /systemEvent\?\.displayText \?\? "Group updated"/);
assert.match(detail, /cell.textLabel\?\.textColor = ChitChatColors.textMuted/);
assert.match(detail, /case let .dateSeparator/);
assert.match(detail, /loadOlderMessages/);
console.log('Native group administration static checks passed: permissions, confirmations, atomic owner-leave request, realtime, event decoding/rendering, theme and pagination. Signed device tests still required.');
